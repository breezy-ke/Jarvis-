/**
 * Concatenates the migrations into one file, and the seed into another.
 *
 * WHY. Without the Supabase CLI the only way to apply this schema is to paste
 * it into the SQL editor in a browser, and there are eleven files that must go
 * in a specific order. Eleven chances to paste 0006 before 0005, or to miss one
 * entirely and not find out until a view is queried weeks later. Two files in a
 * fixed order is a much smaller target.
 *
 * THE TWO FILES DIFFER IN WHETHER THEY CAN BE RE-RUN, which is the main
 * reason they are two files.
 *
 * schema.sql CANNOT. It looks like it can — the tables and indexes all say
 * `if not exists` — but 0005 creates a view that 0009 replaces with a
 * different column list, and Postgres refuses: "cannot drop columns from view".
 * A second apply therefore dies partway through, on an error that says nothing
 * about the real cause. If it fails halfway, reset the database and start clean
 * rather than running it again over the top. On a fresh Supabase project that
 * is Settings → Database → Reset; there is nothing in it worth keeping yet.
 *
 * seed.sql CAN. Every insert in it ends in `on conflict (id) do update`, so
 * re-running refreshes the geography in place instead of duplicating it —
 * verified by applying it three times and watching 6/30/559/238,528 stay put.
 * An earlier version of this comment claimed the opposite and was wrong; it
 * was reasoning about what a seed file usually does rather than reading this
 * one.
 *
 * Generated files are NOT committed. They are derived, they would drift the
 * moment a migration changed, and a stale bundle that looks authoritative is
 * worse than no bundle. `npm run db:bundle` regenerates them in seconds.
 *
 * Run: npm run db:bundle
 */
import { readdir, readFile, writeFile, mkdir } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const OUT = path.join(root, "supabase/bundle");

async function bundle(sourceDir, outFile, title, note) {
  const dir = path.join(root, sourceDir);
  const files = (await readdir(dir)).filter((f) => f.endsWith(".sql")).sort();

  const parts = [
    `-- ${title}`,
    `-- GENERATED by scripts/db/bundle.mjs — do not edit, and do not commit.`,
    `-- Source: ${sourceDir}/ (${files.length} files, in filename order)`,
    `-- Built:  ${new Date().toISOString()}`,
    "--",
    ...note.map((line) => `-- ${line}`),
    "",
  ];

  for (const file of files) {
    const sql = await readFile(path.join(dir, file), "utf8");
    parts.push(
      "",
      `-- ${"=".repeat(70)}`,
      `-- ${file}`,
      `-- ${"=".repeat(70)}`,
      "",
      sql.trimEnd(),
      "",
    );
  }

  await mkdir(OUT, { recursive: true });
  const target = path.join(OUT, outFile);
  const text = parts.join("\n");
  await writeFile(target, text);

  const kb = (Buffer.byteLength(text) / 1024).toFixed(0);
  console.log(`  ${outFile.padEnd(14)} ${String(files.length).padStart(2)} files, ${kb}KB`);
  return files;
}

const schema = await bundle("supabase/migrations", "schema.sql", "Akiyar — full schema", [
  "Run this FIRST, on an EMPTY database, and wait for it to finish.",
  "",
  "NOT re-runnable. It looks idempotent because the tables and indexes say",
  "`if not exists`, but 0005 creates a view that 0009 replaces with a",
  "different column list, so a second apply dies on \"cannot drop columns",
  "from view\". If this fails partway, reset the database rather than",
  "running it again over the top.",
]);

const seed = await bundle("supabase/seed", "seed.sql", "Akiyar — reference data", [
  "Run this AFTER schema.sql has finished.",
  "",
  "Safe to re-run: every insert ends in `on conflict (id) do update`, so a",
  "second run refreshes the geography in place rather than duplicating it.",
  "Verified by applying it three times — 6/30/559/238,528 throughout.",
]);

console.log(`\nwrote supabase/bundle/ — ${schema.length} migrations, ${seed.length} seed file(s)`);
console.log("These are generated and gitignored. Regenerate any time with `npm run db:bundle`.\n");
